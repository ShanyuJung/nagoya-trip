import { writeFile } from "node:fs/promises";
import { places } from "../src/data/places";

const notionHost = "https://rainbow-gosling-80b.notion.site";
const collectionId = "356ecbe1-8409-81c2-91e7-000be4e7955e";
const collectionViewId = "356ecbe1-8409-8177-a50b-000ce8034dd8";
const spaceId = "824d7a7c-93ce-43c5-b8b9-604ef9d574d7";
const dayProperty = "rj]=";
const categoryProperty = ":QwR";
const descriptionProperty = "f.~Z";
const dayOrder = ["11/7", "11/8", "11/9", "11/10", "11/11", "11/12", "11/13", "11/14"];

type RichText = Array<[string, Array<[string, string]>?]>;
type NotionBlock = {
  id: string;
  type: string;
  parent_table?: string;
  properties?: Record<string, RichText>;
};

type NotionQueryResponse = {
  recordMap?: { block?: Record<string, { value?: { value?: NotionBlock } }> };
};

const aliases: Record<string, string[]> = {
  "nara-park": ["吃完麵虐鹿"],
  "nipponbashi-denden-town": ["日本橋當肥宅"],
  "bon-condominium-namba-ebisu": ["BON(1600 check in)"],
  "ise-jingu-naiku": ["皇大神宮 (伊勢神宮 內宮)"],
  "onigiri-gorichan-kuromon": ["おにぎりごりちゃん黒門市場店 (早餐)"],
  "kakinoha-sushi-tanaka-nara": [
    "Kakinoha Sushi Honpo Tanaka Nara Honten 柿の葉すし本舗たなか なら本店 (車上吃)",
  ],
};

function text(value?: RichText) {
  return (
    value
      ?.map(([content]) => content)
      .join("")
      .trim() ?? ""
  );
}

function links(properties: Record<string, RichText> = {}) {
  return Object.values(properties).flatMap((value) =>
    value.flatMap(
      ([, marks]) => marks?.filter(([type]) => type === "a").map(([, url]) => url) ?? [],
    ),
  );
}

function normalize(value: string) {
  return value
    .normalize("NFKC")
    .toLocaleLowerCase()
    .replace(/[（(].*?[）)]/g, "")
    .replace(/[\s・·—–\-_／/]/g, "")
    .replace(/[^\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}a-z0-9]/gu, "");
}

const response = await fetch(`${notionHost}/api/v3/queryCollection`, {
  method: "POST",
  headers: { "content-type": "application/json" },
  body: JSON.stringify({
    collection: { id: collectionId, spaceId },
    collectionView: { id: collectionViewId, spaceId },
    loader: {
      type: "reducer",
      reducers: {
        collection_group_results: { type: "results", limit: 500 },
        "table:uncategorized": { type: "results", limit: 500 },
      },
      searchQuery: "",
      userTimeZone: "Asia/Taipei",
    },
  }),
});

if (!response.ok) throw new Error(`Notion query failed: ${response.status}`);
const query = (await response.json()) as NotionQueryResponse;
const rows = Object.values(query.recordMap?.block ?? {})
  .map((entry) => entry.value?.value)
  .filter(
    (block): block is NotionBlock => block?.type === "page" && block.parent_table === "collection",
  )
  .flatMap((block, sourceIndex) => {
    const dayLabel = text(block.properties?.[dayProperty]);
    const day = dayOrder.find((candidate) => dayLabel.startsWith(candidate));
    if (!day) return [];
    const title = text(block.properties?.title);
    const rowLinks = links(block.properties);
    const normalizedTitle = normalize(title);
    const place = places.find((candidate) => {
      const candidateLinks = [candidate.maps, candidate.official, candidate.tabelog?.url].filter(
        Boolean,
      );
      if (candidateLinks.some((url) => rowLinks.includes(url!))) return true;
      const names = [candidate.name, candidate.nameJa, ...(aliases[candidate.id] ?? [])]
        .map(normalize)
        .filter(Boolean);
      return names.some(
        (name) =>
          normalizedTitle === name ||
          (name.length >= 5 && (normalizedTitle.includes(name) || name.includes(normalizedTitle))),
      );
    });
    return [
      {
        id: block.id,
        day,
        dayLabel,
        title,
        category: text(block.properties?.[categoryProperty]) || "行程",
        description: text(block.properties?.[descriptionProperty]),
        placeId: place?.id,
        sourceIndex,
      },
    ];
  });

const days = dayOrder.map((day) => {
  const items = rows.filter((row) => row.day === day).sort((a, b) => a.sourceIndex - b.sourceIndex);
  return {
    id: day,
    label: items[0]?.dayLabel ?? day,
    items: items.map((item) => ({
      id: item.id,
      title: item.title,
      category: item.category,
      description: item.description,
      ...(item.placeId ? { placeId: item.placeId } : {}),
    })),
  };
});

const source = `// Generated by scripts/sync-notion-itinerary.ts\nexport type ItineraryItem = {\n  id: string;\n  title: string;\n  category: string;\n  description: string;\n  placeId?: string;\n};\n\nexport type ItineraryDay = {\n  id: string;\n  label: string;\n  items: ItineraryItem[];\n};\n\nexport const itineraryDays: ItineraryDay[] = ${JSON.stringify(days, null, 2)};\n`;

await writeFile("src/data/itinerary.ts", source);
console.log(
  `Synced ${rows.length} scheduled Notion rows; ${rows.filter((row) => row.placeId).length} matched map places.`,
);
for (const day of days) console.log(`${day.id}: ${day.items.length} items`);
